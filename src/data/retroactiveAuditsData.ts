/**
 * Combina auditorias dinâmicas com o histórico retroativo sem duplicar registros por ID ou Mapa.
 */
export function mergeWithRetroactiveAudits(liveAudits: AuditSession[]): AuditSession[] {
  if (!liveAudits || liveAudits.length === 0) {
    return RETROACTIVE_AUDITS;
  }
  
  const existingIds = new Set(liveAudits.map(a => (a.id || "").toLowerCase()));
  const existingMaps = new Set(liveAudits.map(a => (a.routeMap || "").replace(/^0+/, "").toLowerCase()));
  
  const combined = [...liveAudits];
  
  for (const retro of RETROACTIVE_AUDITS) {
    const retroId = (retro.id || "").toLowerCase();
    const retroMap = (retro.routeMap || "").replace(/^0+/, "").toLowerCase();
    
    if (!existingIds.has(retroId) && !existingMaps.has(retroMap)) {
      combined.push(retro);
    }
  }
  
  return combined;
}
